#!/usr/bin/env python3
"""Writes runtime/rando/apply/ours_world_data.cpp: what the seed build's entrance step (runtime/rando/apply/ours_world.cpp,
entrance_logic.apply_rooms in decide mode) reads from tools/rando/loading_zones.json - each loading zone's level, room,
index and parameters - as one JSON document the C++ parses.

    python3 tools/rando/export_ours_world.py          # rewrite the file
    python3 tools/rando/export_ours_world.py --check  # exit 1 when it's out of date
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'ours_world_data.cpp')


def data():
    zones = json.load(open(os.path.join(HERE, 'loading_zones.json')))
    return [[z['level'], z['room'], z['index'], z['params']] for z in zones]


def c_literal(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render():
    text = json.dumps(data(), ensure_ascii=True, separators=(',', ':'))
    parts = [text[i:i + 2000] for i in range(0, len(text), 2000)]  # (MSVC: a string literal stays under 16 KB)
    lines = ['// Generated by tools/rando/export_ours_world.py from tools/rando/loading_zones.json ([level, room, index,',
             "// parameters] per loading zone). Don't edit: rerun the script.",
             '#include <string>', '', 'namespace rando {', 'namespace las {', '',
             'static const char *const kZoneParts[] = {']
    lines += ['    ' + c_literal(p) + ',' for p in parts]
    lines += ['};', '',
              'std::string loading_zones_json() {',
              '    std::string s;',
              '    for (const char *p : kZoneParts) s += p;',
              '    return s;',
              '}', '', '}  // namespace las', '}  // namespace rando', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_ours_world.py')
            return 1
        print(f'{os.path.relpath(OUT, ROOT)}: up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
