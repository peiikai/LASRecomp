#!/usr/bin/env python3
"""Writes runtime/rando/apply/las_enemies_data.cpp: what the enemy randomizer's port (las_enemies.cpp;
docs/randomizer.md, stage 5) needs from the Python, so the two can't drift:

  - LAS-Randomizer's ENEMY_DATA (RandomizerCore/Data/enemies.yml, MIT, Owen-Splat and contributors): the actors in
    the file's order (id, terrain, enemy flag, parameters), the chest enemies, the excluded actors, the 2D rooms and
    the level folders randomizeEnemies walks;
  - LAS Recomp's constants in RandomizerCore/Randomizers/enemies.py (the mini-bosses, the room and group rules) and
    tools/rando/miniboss_guard.py's ANYWHERE.

    <LAS venv python> tools/rando/export_las_enemies.py          # rewrite the file
    <LAS venv python> tools/rando/export_las_enemies.py --check  # exit 1 when the file isn't what the Python gives

Declarations: runtime/rando/apply/las_enemies.h.
"""
import os
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
LAS = os.path.join(ROOT, 'third_party', 'LAS-Randomizer')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'las_enemies_data.cpp')

sys.modules.setdefault('PySide6', types.ModuleType('PySide6'))
sys.modules.setdefault('PySide6.QtCore', types.ModuleType('PySide6.QtCore'))
sys.path.insert(0, LAS)
sys.path.insert(0, HERE)
sys.argv[0] = os.path.join(LAS, 'randomizer.py')  # (LAS finds its data next to argv[0] when run from source)

from RandomizerCore.Randomizers import enemies  # noqa: E402
from RandomizerCore.randomizer_data import ENEMY_DATA  # noqa: E402
import miniboss_guard  # noqa: E402


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def value(v):
    """One parameter value as EnemyValue: a string (bytes in the room), an int or a float."""
    if isinstance(v, bool):
        raise TypeError(f'enemy parameter {v!r}: a bool')
    if isinstance(v, (str, bytes)):
        s = v.decode('utf-8') if isinstance(v, bytes) else v
        return f'{{EnemyValue::Str, {c_str(s)}, 0, 0}}'
    if isinstance(v, int):
        return f'{{EnemyValue::Int, "", {v}, 0}}'
    if isinstance(v, float):
        return f'{{EnemyValue::Float, "", 0, {v!r}}}'
    raise TypeError(f'enemy parameter {v!r}')


def param(p):
    """A parameter: a list (random.choice of its values) or one value."""
    if isinstance(p, list):
        return '{true, {' + ', '.join(value(x) for x in p) + '}}'
    return '{false, {' + value(p) + '}}'


def wrapped(head, items):
    """head + '{a, b, ...};' within 120 columns (continuation lines indented by 4)."""
    line, out = head + '{', []
    for i, it in enumerate(items):
        piece = it + (', ' if i + 1 < len(items) else '')
        if len(line) + len(piece.rstrip()) > 118:
            out.append(line.rstrip())
            line = '    '
        line += piece
    out.append(line + '};')
    return '\n'.join(out)


def ints(head, xs):
    return wrapped(head, [f'0x{x:X}' for x in xs])


def strs(head, xs):
    return wrapped(head, [c_str(x) for x in xs])


def generate():
    L = ['// Generated by tools/rando/export_las_enemies.py from LAS-Randomizer\'s RandomizerCore/Data/enemies.yml '
         '(MIT,',
         '// Owen-Splat and contributors) and LAS Recomp\'s RandomizerCore/Randomizers/enemies.py and',
         '// tools/rando/miniboss_guard.py.',
         '// Do not edit: run the script.',
         '#include "las_enemies.h"', '', 'namespace rando {', 'namespace las {', 'namespace enemy_data {', '']
    L.append('const std::vector<EnemyActor> ACTORS = {')
    for name, v in ENEMY_DATA['Actors'].items():
        ps = v.get('parameters')
        row = (f'    {{{c_str(name)}, 0x{v["id"]:X}, {c_str(v["type"])}, {int(v["enemy"])}, '
               f'{str(bool(v.get("minibosses-only"))).lower()}, ')
        if ps is None:
            L.append(row + 'false, {}},')
            continue
        params = [param(p) for p in ps]
        if len(row) + sum(len(x) + 2 for x in params) + 10 <= 120:
            L.append(row + 'true, {' + ', '.join(params) + '}},')
        else:  # (one parameter per line)
            L.append(row + 'true,')
            L += [f'     {"{" if i == 0 else " "}{x}' + ('}},' if i + 1 == len(params) else ',')
                  for i, x in enumerate(params)]
    L += ['};', '']
    L.append(ints('const std::vector<int> CHEST_ENEMIES = ', ENEMY_DATA["Chest_Enemies"]))
    L.append('const std::vector<std::pair<const char *, std::vector<int>>> EXCLUDED_ACTORS = {')
    L += [f'    {{{c_str(k)}, {{{", ".join(str(x) for x in v)}}}}},' for k, v in ENEMY_DATA['Excluded_Actors'].items()]
    L += ['};']
    L.append(strs('const std::vector<const char *> ROOMS_2D = ', ENEMY_DATA["2D_Rooms"]))
    L.append(strs('const std::vector<const char *> INCLUDED_FOLDERS = ', ENEMY_DATA["Included_Folders"]))
    L.append('')
    L.append('const std::vector<std::pair<int, std::vector<EnemyValue>>> FIELD_MINIBOSSES = {')
    for k in sorted(enemies.FIELD_MINIBOSSES):
        L.append(f'    {{0x{k:X}, {{{", ".join(value(x) for x in enemies.FIELD_MINIBOSSES[k])}}}}},')
    L += ['};']
    L.append('const std::vector<std::pair<int, std::vector<std::vector<EnemyValue>>>> MINIBOSS_VARIANTS = {')
    for k, vs in enemies.MINIBOSS_VARIANTS.items():
        L.append(f'    {{0x{k:X}, {{' + ', '.join('{' + ', '.join(value(x) for x in v) + '}' for v in vs) + '}},')
    L += ['};']
    L.append(ints('const std::vector<int> ANY_TERRAIN_MINIBOSSES = ', sorted(enemies.ANY_TERRAIN_MINIBOSSES)))
    L.append('const std::vector<std::pair<int, int>> NEEDS_ROOM = {' +
             ', '.join(f'{{0x{k:X}, {v}}}' for k, v in enemies.NEEDS_ROOM.items()) + '};')
    L.append(f'const int BIG_ROOM = {enemies.BIG_ROOM};')
    L.append(ints('const std::vector<int> SMALL_MINIBOSSES = ', sorted(enemies.SMALL_MINIBOSSES)))
    L.append(f'const double MB_GAP = {enemies.MB_GAP!r};')
    L.append(strs('const std::vector<const char *> SMALL_ONLY_SCREENS = ', sorted(enemies.SMALL_ONLY_SCREENS)))
    L.append(f'const bool SMALL_ON_AIR = {str(bool(enemies.SMALL_ON_AIR)).lower()};')
    L.append(ints('const std::vector<int> SOLID_OBJECTS = ', sorted(enemies.SOLID_OBJECTS)))
    L.append('const std::vector<double> MINIBOSS_CHANCES = {' +
             ', '.join(repr(float(x)) for x in enemies.MINIBOSS_CHANCES) + '};')
    L.append(ints('const std::vector<int> NO_2D = ', enemies.NO_2D))
    L.append(ints('const std::vector<int> FLY_BOMBS = ', enemies.FLY_BOMBS))
    L.append(ints('const std::vector<int> BLOCKING = ', enemies.BLOCKING))
    L.append(ints('const std::vector<int> ONE_PER_ROOM = ', enemies.ONE_PER_ROOM))
    L.append(ints('const std::vector<int> ARENA_TYPES = ', sorted(enemies.ARENA_TYPES)))
    L.append('const std::vector<std::pair<const char *, int>> STAIR_GUARDS = {' +
             ', '.join(f'{{{c_str(k)}, {v}}}' for k, v in enemies.STAIR_GUARDS.items()) + '};')
    L.append(f'const int OBJ_CLOSED_DOOR = 0x{enemies.OBJ_CLOSED_DOOR:X};')
    L.append(ints('const std::vector<int> MARK_ANYWHERE = ', sorted(miniboss_guard.ANYWHERE)))
    L += ['', '}  // namespace enemy_data', '}  // namespace las', '}  // namespace rando', '']
    return '\n'.join(L)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_las_enemies.py',
                  file=sys.stderr)
            return 1
        print(f'{os.path.relpath(OUT, ROOT)} is current')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
