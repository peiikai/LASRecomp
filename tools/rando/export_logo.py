#!/usr/bin/env python3
"""Writes runtime/rando/apply/logo_data.cpp: LAS-Randomizer's title banner (third_party/LAS-Randomizer/Resources/
randomizer.png, MIT) for the seed build's title logo step (runtime/rando/apply/textures.cpp), as run-length encoded
gray + alpha pixels: (run length - 1, gray, alpha) triplets, rows top to bottom.

    python3 tools/rando/export_logo.py          # rewrite the file (needs Pillow: the LAS venv's Python)
    python3 tools/rando/export_logo.py --check  # exit 1 when it's out of date
"""
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SRC = os.path.join(ROOT, 'third_party', 'LAS-Randomizer', 'Resources', 'randomizer.png')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'logo_data.cpp')


def render():
    from PIL import Image
    im = Image.open(SRC)
    if im.mode != 'LA':
        raise SystemExit(f'{SRC}: expected a gray + alpha image, got {im.mode}')
    px = list(zip(im.getchannel(0).getdata(), im.getchannel(1).getdata()))
    runs = []
    i = 0
    while i < len(px):
        n = 1
        while i + n < len(px) and n < 256 and px[i + n] == px[i]:
            n += 1
        runs += [n - 1, px[i][0], px[i][1]]
        i += n
    lines = ['// Generated by tools/rando/export_logo.py from third_party/LAS-Randomizer/Resources/randomizer.png',
             '// (LAS-Randomizer, MIT, Owen-Splat and contributors). Do not edit.',
             '#include "textures.h"', '', 'namespace rando {', '',
             f'const int LOGO_W = {im.width}, LOGO_H = {im.height};',
             f'const size_t LOGO_RLE_SIZE = {len(runs)};', 'const unsigned char LOGO_RLE[] = {']
    for k in range(0, len(runs), 30):
        lines.append('    ' + ','.join(str(v) for v in runs[k:k + 30]) + ',')
    lines += ['};', '', '}  // namespace rando', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_logo.py')
            return 1
        print(f'{os.path.relpath(OUT, ROOT)}: up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
