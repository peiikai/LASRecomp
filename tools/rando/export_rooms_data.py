#!/usr/bin/env python3
"""Writes runtime/rando/apply/rooms_data.cpp: what the seed build's dungeon room shuffle step
(runtime/rando/apply/rooms.cpp, dungeon_gen.write_all) reads from tools/rando/room_catalog.json and tools/rando/rooms.py:
every catalogued room with the cells of its multi-cell room ('unit') and whether it holds a crystal switch, and the
rooms no seed reaches (rooms.DEAD).

    python3 tools/rando/export_rooms_data.py          # rewrite the file
    python3 tools/rando/export_rooms_data.py --check  # exit 1 when it's out of date
"""
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
CATALOG = os.path.join(ROOT, 'tools', 'rando', 'room_catalog.json')
ROOMS_PY = os.path.join(ROOT, 'tools', 'rando', 'rooms.py')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'rooms_data.cpp')


def dead_rooms():
    """rooms.DEAD, read from its source (rooms.py imports LAS's room code, which this script doesn't need)."""
    src = open(ROOMS_PY).read()
    m = re.search(r"^DEAD = \{f'Lv07EagleTower_\{c\}' for c in \(([^)]*)\)\}", src, re.M)
    if not m:
        raise SystemExit('rooms.py: DEAD not found in the expected form - update export_rooms_data.py')
    return sorted('Lv07EagleTower_' + c for c in re.findall(r"'([0-9A-Z]+)'", m.group(1)))


def render():
    cat = json.load(open(CATALOG))
    lines = ['// Generated by tools/rando/export_rooms_data.py from tools/rando/room_catalog.json and rooms.py. Do not edit.',
             '#include "rooms.h"', '', 'namespace rando {', '',
             '// (room, its unit\'s cells joined by spaces, holds a crystal switch)',
             'const RoomEntry ROOM_CATALOG[] = {']
    for k, v in cat.items():  # (the catalog's own order)
        lines.append('    {"%s", "%s", %s},' % (k, ' '.join(v['unit']), 'true' if 'ObjCrystalSw' in v.get('actors', ()) else 'false'))
    lines += ['};', f'const size_t ROOM_CATALOG_SIZE = {len(cat)};', '',
              'const char *const DEAD_ROOMS[] = {' + ', '.join(f'"{d}"' for d in dead_rooms()) + '};',
              f'const size_t DEAD_ROOMS_SIZE = {len(dead_rooms())};', '', '}  // namespace rando', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_rooms_data.py')
            return 1
        print(f'{os.path.relpath(OUT, ROOT)}: up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
