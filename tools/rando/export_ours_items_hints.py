#!/usr/bin/env python3
"""Writes runtime/rando/apply/ours_items_hints_data.cpp: the text tables of tools/rando/hint_sheet.py and seed_hints.py
(English place and item wording, the statue entries, our sentences in the other languages) as C++, for the ported Hint
Sheet and hint steps (docs/randomizer.md, stage 3), so the two can't drift.

    python3 tools/rando/export_ours_items_hints.py          # rewrite the file
    python3 tools/rando/export_ours_items_hints.py --check  # exit 1 when the file isn't what the Python tables give

Plain Python 3: the modules are read without importing them. Tables keep the Python dicts' order (sets: sorted).
Declarations: runtime/rando/apply/ours_items_hints_data.h.
"""
import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HS = os.path.join(ROOT, 'tools', 'rando', 'hint_sheet.py')
SH = os.path.join(ROOT, 'tools', 'rando', 'seed_hints.py')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'ours_items_hints_data.cpp')


def module_globals(path):
    """The module's top-level constant assignments, in file order (names of earlier ones may be used: NAME)."""
    with open(path, encoding='utf-8') as f:
        tree = ast.parse(f.read())
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                out[node.targets[0].id] = ast.literal_eval(node.value)
            except ValueError:
                try:
                    out[node.targets[0].id] = eval(compile(ast.Expression(node.value), path, 'eval'),
                                                   {'__builtins__': {}}, dict(out))
                except Exception:
                    pass
    return out


def c_str(s):
    out = '"'
    for b in s.encode('utf-8'):
        ch = chr(b)
        if ch in '"\\':
            out += '\\' + ch
        elif ch == '\n':
            out += '\\n'
        elif 32 <= b < 127 and ch != '?':
            out += ch
        else:
            out += '\\%03o' % b
    return out + '"'


def str_table(name, d):
    rows = ''.join(f'    {{{c_str(k)}, {c_str(v)}}},\n' for k, v in d.items())
    return f'const StrTable {name} = {{\n{rows}}};\n'


def list_table(name, d):
    rows = ''.join(f'    {{{c_str(k)}, {{{", ".join(c_str(x) for x in v)}}}}},\n' for k, v in d.items())
    return f'const ListTable {name} = {{\n{rows}}};\n'


def str_list(name, v):
    return f'const std::vector<const char *> {name} = {{' + ', '.join(c_str(x) for x in v) + '};\n'


def segs(name, v):
    return f'const std::vector<std::pair<const char *, bool>> {name} = {{' + \
        ', '.join(f'{{{c_str(t)}, {"true" if r else "false"}}}' for t, r in v) + '};\n'


def text_table(name, d):
    out = f'const text::TextTable {name} = {{\n'
    for key, langs in d.items():
        out += f'    {{{c_str(key)}, {{\n'
        for lang, v in langs.items():
            out += f'        {{{c_str(lang)}, {{{c_str(v)}}}}},\n'
        out += '    }},\n'
    return out + '};\n'


def generate():
    hs, sh = module_globals(HS), module_globals(SH)
    L = ['// Generated by tools/rando/export_ours_items_hints.py from tools/rando/hint_sheet.py and seed_hints.py. Don\'t',
         '// edit: rerun the script.', '#include "ours_items_hints_data.h"', '', 'namespace rando {', 'namespace ours {',
         'namespace hints {', '', '// hint_sheet.py']
    for n in ('ENTRY', 'DONE', 'MODEL_NPC'):
        L.append(f'const char *const {n} = {c_str(hs[n])};')
    L.append(f'const int LINE = {hs["LINE"]};\n')
    for n in ('DUNGEON', 'DUNGEON_KEY', 'LEVEL_DUNGEON', 'AREA', 'ITEM', 'DUNGEON_ITEM', 'PLACE'):
        L.append(str_table(n, hs[n]))
    L.append(list_table('AREA_WORDS', hs['AREA_WORDS']))
    L.append(str_list('PLURAL', sorted(hs['PLURAL'])))
    L.append(str_list('BOSSES', sorted(hs['BOSSES'])))
    L.append(segs('GET_TEXT', hs['GET_TEXT']))
    L.append(segs('DONE_TEXT', hs['DONE_TEXT']))
    L.append(str_table('ACTOR_NAME', {k.decode(): v for k, v in hs['ACTOR_NAME'].items()}))
    L.append('// seed_hints.py')
    for n in ('FIELD_OWLS', 'DUNGEON_OWLS', 'SPLIT', 'QUEST_EN', 'QUEST_LABEL'):
        L.append(str_table(n, sh[n]))
    L.append(text_table('T', sh['T']))
    L += ['}  // namespace hints', '}  // namespace ours', '}  // namespace rando', '']
    return '\n'.join(L)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        with open(OUT, encoding='utf-8') as f:
            same = f.read() == text
        print('ours_items_hints_data.cpp is ' + ('current' if same else 'OUT OF DATE: rerun tools/rando/export_ours_items_hints.py'))
        sys.exit(0 if same else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
