#!/usr/bin/env python3
"""Writes runtime/rando/apply/ours_items_text_data.cpp: the sentence and name tables of tools/rando/loc_text.py (our own
texts in every language, the game's message labels for item and place names) as C++, for the ported item steps
(docs/randomizer.md, stage 3), so the two can't drift.

    python3 tools/rando/export_ours_items_text.py          # rewrite the file
    python3 tools/rando/export_ours_items_text.py --check  # exit 1 when the file isn't what loc_text.py gives

Plain Python 3: loc_text.py is read without importing it. Tables keep the Python dicts' order. Declarations:
runtime/rando/apply/ours_items_text.h.
"""
import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'tools', 'rando', 'loc_text.py')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'ours_items_text_data.cpp')


def module_globals(path):
    with open(path, encoding='utf-8') as f:
        tree = ast.parse(f.read())
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            v = node.value
            try:
                if isinstance(v, ast.Call) and isinstance(v.func, ast.Name) and v.func.id == 'set' and len(v.args) == 1:
                    out[node.targets[0].id] = set(ast.literal_eval(v.args[0]))  # (set('...'))
                else:
                    out[node.targets[0].id] = ast.literal_eval(v)
            except ValueError:
                pass
    return out


def c_str(s):
    """A C string literal of the text's UTF-8 (octal escapes outside printable ASCII: they can't run into the next
    character, and the source stays ASCII for every compiler)."""
    out = '"'
    for b in s.encode('utf-8'):
        ch = chr(b)
        if ch in '"\\':
            out += '\\' + ch
        elif ch == '\n':
            out += '\\n'
        elif 32 <= b < 127 and ch != '?':  # ('?': no trigraphs)
            out += ch
        else:
            out += '\\%03o' % b
    return out + '"'


def str_table(name, d):
    rows = ''.join(f'    {{{c_str(k)}, {c_str(v)}}},\n' for k, v in d.items())
    return f'const StrTable {name} = {{\n{rows}}};\n'


def text_table(name, d):
    out = f'const TextTable {name} = {{\n'
    for key, langs in d.items():
        out += f'    {{{c_str(key)}, {{\n'
        for lang, v in langs.items():
            items = v if isinstance(v, list) else [v]
            out += f'        {{{c_str(lang)}, {{{", ".join(c_str(x) for x in items)}}}}},\n'
        out += '    }},\n'
    return out + '};\n'


def generate():
    g = module_globals(SRC)
    L = ['// Generated by tools/rando/export_ours_items_text.py from tools/rando/loc_text.py. Don\'t edit: rerun the script.',
         '#include "ours_items_text.h"', '', 'namespace rando {', 'namespace ours {', 'namespace text {', '']
    L.append(str_table('FOLDERS', g['FOLDERS']))
    L.append('const std::vector<std::pair<const char *, int>> LINE = {\n' +
             ''.join(f'    {{{c_str(k)}, {v}}},\n' for k, v in g['LINE'].items()) + '};\n')
    L.append('const std::vector<const char *> CHAR_WRAP = {' + ', '.join(c_str(x) for x in sorted(g['CHAR_WRAP'])) + '};\n')
    L.append('const std::vector<const char *> NO_LINE_START = {' +
             ', '.join(c_str(x) for x in sorted(g['NO_LINE_START'])) + '};\n')
    L.append(str_table('ITEM_LABEL', g['ITEM_LABEL']))
    L.append(str_table('AREA_LABEL', g['AREA_LABEL']))
    for n in ('T', 'DETAIL', 'ITEM_OWN'):
        L.append(text_table(n, g[n]))
    L += ['}  // namespace text', '}  // namespace ours', '}  // namespace rando', '']
    return '\n'.join(L)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        with open(OUT, encoding='utf-8') as f:
            same = f.read() == text
        print('ours_items_text_data.cpp is ' + ('current' if same else 'OUT OF DATE: rerun tools/rando/export_ours_items_text.py'))
        sys.exit(0 if same else 1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
