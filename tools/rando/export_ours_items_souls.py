#!/usr/bin/env python3
"""Writes runtime/rando/apply/ours_items_souls_data.cpp: what souls.apply reads from tools/rando/room_catalog.json
(the sides of each dungeon room's boss doors: boss_doors leaves the shutters on those sides alone) as C++, for the
ported souls step (runtime/rando/apply/ours_items_souls.cpp), so the two can't drift.

    python3 tools/rando/export_ours_items_souls.py          # rewrite the file
    python3 tools/rando/export_ours_items_souls.py --check  # exit 1 when the file isn't what the catalog gives

Plain Python 3. Rooms in the catalog's order.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'tools', 'rando', 'room_catalog.json')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'ours_items_souls_data.cpp')
LEVELS = ('Lv10ClothesDungeon', 'Lv01TailCave', 'Lv02BottleGrotto', 'Lv03KeyCavern', 'Lv04AnglersTunnel',
          'Lv05CatfishsMaw', 'Lv06FaceShrine', 'Lv07EagleTower', 'Lv08TurtleRock')  # (souls.BOSSES' levels)


def generate():
    with open(SRC) as f:
        cat = json.load(f)
    L = ['// Generated by tools/rando/export_ours_items_souls.py from tools/rando/room_catalog.json. Don\'t edit: rerun',
         '// the script.', '#include <string>', '#include <utility>', '#include <vector>', '', 'namespace rando {',
         'namespace ours {', '',
         '// room -> the sides of its boss doors (souls.boss_doors: {d[0] for d in cat[room][\'doors\'] if \'bossdoor\' in d[2]})',
         'extern const std::vector<std::pair<const char *, const char *>> SOUL_BOSS_DOOR_SIDES;',
         'const std::vector<std::pair<const char *, const char *>> SOUL_BOSS_DOOR_SIDES = {']
    for room, v in cat.items():
        if room.rsplit('_', 1)[0] not in LEVELS:
            continue
        sides = ''.join(sorted({d[0] for d in v.get('doors', []) if 'bossdoor' in d[2]}))
        if sides:
            L.append(f'    {{"{room}", "{sides}"}},')
    L += ['};', '', '}  // namespace ours', '}  // namespace rando', '']
    return '\n'.join(L)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        with open(OUT) as f:
            same = f.read() == text
        print('ours_items_souls_data.cpp is ' + ('current' if same else 'OUT OF DATE: rerun tools/rando/export_ours_items_souls.py'))
        sys.exit(0 if same else 1)
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
