    sys.path.insert(0, LAS)
    cwd, argv0 = os.getcwd(), sys.argv[0]
    os.chdir(LAS)  # (LAS resolves its data from argv[0], relative to its folder)
    sys.argv[0] = os.path.join(LAS, 'randomizer.py')
    try:
        from RandomizerCore import randomizer_data as rd
        from RandomizerCore.Randomizers import data as las_data
    finally:
        os.chdir(cwd)
        sys.argv[0] = argv0
    import bushes
