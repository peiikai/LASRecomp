#!/usr/bin/env python3
"""Writes runtime/rando/apply/las_data.cpp: LAS-Randomizer's constant tables (RandomizerCore/Randomizers/data.py, the
flags flags.makeFlags adds to GlobalFlags.gsheet, player_start's flag lists) as C++, so the ported generator steps
(docs/randomizer.md, stage 3) read the same tables the Python does and the two can't drift.

    python3 tools/rando/export_las_data.py          # rewrite the file
    python3 tools/rando/export_las_data.py --check  # exit 1 when the file isn't what the Python tables give

Plain Python 3, no LAS venv: the modules are read without importing their dependencies. The output is
deterministic (tables in the Python's own order). Declarations: runtime/rando/apply/las_data.h.
"""
import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CORE = os.path.join(ROOT, 'third_party', 'LAS-Randomizer', 'RandomizerCore')
OUT = os.path.join(ROOT, 'runtime', 'rando', 'apply', 'las_data.cpp')

STRINGS = ('SWORD_FOUND_FLAG', 'SHIELD_FOUND_FLAG', 'BRACELET_FOUND_FLAG', 'LENS_FOUND_FLAG', 'RED_TUNIC_FOUND_FLAG',
           'BLUE_TUNIC_FOUND_FLAG', 'GORIYA_FLAG', 'MAMU_FLAG', 'MANBO_FLAG', 'BEACH_LOOSE_FLAG', 'WOODS_LOOSE_FLAG',
           'POTHOLE_FLAG', 'DREAM_SHRINE_FLAG', 'ROOSTER_CAVE_FLAG', 'MERMAID_CAVE_FLAG', 'BOMBS_FOUND_FLAG',
           'ROOSTER_FOUND_FLAG', 'BOWWOW_FOUND_FLAG', 'INFINITE_BOMBS', 'INFINITE_ARROWS', 'INFINITE_POWDER',
           'HIGH_JUMP')
STR_MAPS = ('INSTRUMENT_FLAGS', 'HEART_FLAGS', 'CHEST_ROOMS', 'PANEL_CHEST_ROOMS', 'SMALL_KEY_ROOMS',
            'GOLDEN_LEAF_ROOMS', 'INSTRUMENT_ROOMS', 'HEART_ROOMS', 'ITEM_MODELS', 'CHEST_TEXTURES')
NUM_MAPS = ('CHEST_SIZES', 'MODEL_SIZES', 'MODEL_ROTATIONS')


def module_globals(path, names=None):
    """The module's top-level constant assignments (literals only), in file order."""
    with open(path) as f:
        tree = ast.parse(f.read())
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if names is None or name in names:
                try:
                    out[name] = ast.literal_eval(node.value)
                except ValueError:
                    pass
    return out


def global_flags():
    """flags.makeFlags' flags with their indexes: run it on a stand-in sheet (the module imports nothing)."""
    ns = {}
    with open(os.path.join(CORE, 'Randomizers', 'flags.py')) as f:
        exec(compile(f.read(), 'flags.py', 'exec'), ns)
    sheet, flags = ns['makeFlags']({'values': []})
    return list(flags.items())


def c_str(s):
    out = '"'
    for ch in s:
        if ch in '"\\':
            out += '\\' + ch
        elif ch == '\n':
            out += '\\n'
        elif 32 <= ord(ch) < 127:
            out += ch
        else:
            raise ValueError(f'unexpected character {ch!r}')
    return out + '"'


def c_num(v):
    r = repr(float(v))
    return r if ('.' in r or 'e' in r) else r + '.0'


def generate():
    data = module_globals(os.path.join(CORE, 'Randomizers', 'data.py'))
    ps = module_globals(os.path.join(CORE, 'Randomizers', 'player_start.py'), ('START_FLAGS', 'BOSS_FLAGS', 'MESSAGE_FLAGS'))
    L = ['// Generated by tools/rando/export_las_data.py from LAS-Randomizer\'s RandomizerCore (MIT, Owen-Splat and',
         '// contributors): Randomizers/data.py, flags.py (makeFlags), player_start.py. Don\'t edit: rerun the script.',
         '#include "las_data.h"', '', 'namespace rando {', 'namespace las {', 'namespace data {', '']
    for n in STRINGS:
        L.append(f'const char *const {n} = {c_str(data[n])};')
    L.append('')
    for n in STR_MAPS:
        L.append(f'const StrTable {n} = {{')
        L += [f'    {{{c_str(k)}, {c_str(v)}}},' for k, v in data[n].items()]
        L += ['};', '']
    for n in NUM_MAPS:
        L.append(f'const NumTable {n} = {{')
        L += [f'    {{{c_str(k)}, {c_num(v)}}},' for k, v in data[n].items()]
        L += ['};', '']
    L.append('const std::vector<DungeonEntrance> DUNGEON_ENTRANCES = {')
    for k, (a, b, c, d, e) in data['DUNGEON_ENTRANCES'].items():
        L.append(f'    {{{c_str(k)}, {c_str(a)}, {c_str(b)}, {c_str(c)}, {c_str(d)}, {int(e)}}},')
    L += ['};', '']
    L.append('const std::vector<DungeonMapIcon> DUNGEON_MAP_ICONS = {')
    L += [f'    {{{c_str(k)}, {c_str(a)}, {c_str(b)}}},' for k, (a, b) in data['DUNGEON_MAP_ICONS'].items()]
    L += ['};', '']
    L.append('const std::vector<std::pair<const char *, std::vector<int>>> WATER_LOADING_ZONES = {')
    L += [f'    {{{c_str(k)}, {{{", ".join(str(int(i)) for i in v)}}}}},' for k, v in data['WATER_LOADING_ZONES'].items()]
    L += ['};', '']
    for n, vals in (('BGM_TRACKS', data['BGM_TRACKS']), ('START_FLAGS', ps['START_FLAGS']),
                    ('BOSS_FLAGS', ps['BOSS_FLAGS']), ('MESSAGE_FLAGS', ps['MESSAGE_FLAGS'])):
        L.append(f'const std::vector<const char *> {n} = {{')
        L += [f'    {c_str(v)},' for v in vals]
        L += ['};', '']
    L.append('const std::vector<std::pair<const char *, int>> GLOBAL_FLAGS = {')
    L += [f'    {{{c_str(k)}, {v}}},' for k, v in global_flags()]
    L += ['};', '', '}  // namespace data', '}  // namespace las', '}  // namespace rando', '']
    return '\n'.join(L)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_las_data.py', file=sys.stderr)
            return 1
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
