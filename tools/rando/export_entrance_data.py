#!/usr/bin/env python3
"""Writes runtime/rando/solve/entrances_data.cpp: what the native entrance shuffle (runtime/rando/solve/entrances.cpp;
docs/randomizer.md, stage 5) reads, as one JSON document the C++ parses (Value::parse_json, dict order kept):

  - tools/rando/entrance_data.yml, whole (its door dicts end up in the seed's 'ent' as they are);
  - entrance_logic.py's tables (KEEP, INSIDE_TOKENS, the raft dock, DUNGEON_DOORS, the Face Shrine terms, CONNECTORS,
    POCKETS, POCKET_TILES, REGION_PATCHES);
  - hookshot_logic.ROUTES (hookshot-anything is applied inside the shuffle's logic rebuild);
  - what shopsanity / trendsanity hand the shuffle (their locations inside shuffled interiors, as add_to_logic returns
    them), the bush / rock actor types and the apple trees' stand tiles (the pocket test of Field checks).

    python3 tools/rando/export_entrance_data.py          # rewrite the file
    python3 tools/rando/export_entrance_data.py --check  # exit 1 when it's out of date

Needs PyYAML (the LAS venv has it).
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'runtime', 'rando', 'solve', 'entrances_data.cpp')
sys.path.insert(0, HERE)

import apple_trees  # noqa: E402
import bushes  # noqa: E402
import entrance_logic as el  # noqa: E402
import hookshot_logic  # noqa: E402
import rocks  # noqa: E402
import shopsanity  # noqa: E402
import trendsanity  # noqa: E402


def sanity_inside(mod):
    """{door: [[location, condition]]} as mod.add_to_logic returns it (run on stand-in dicts)."""
    logic = collections.defaultdict(lambda: {'content': None})
    items = collections.defaultdict(lambda: {'quantity': 0})
    got = mod.add_to_logic(logic, items, {'excluded-locations': set()})
    return {door: [list(x) for x in its] for door, its in got.items()}


def data():
    return {
        'entrance_data': el.load(),
        'keep': sorted(el.KEEP),
        'inside_tokens': [[loc, token, door] for (loc, token), door in el.INSIDE_TOKENS.items()],
        'raft_dock': el.RAFT_DOCK,
        'raft_patches': [list(p) for p in el.RAFT_PATCHES],
        'dungeon_doors': el.DUNGEON_DOORS,
        'd6_entry': el.D6_ENTRY,
        'd6_front': list(el.D6_FRONT),
        'd6_rest': el.D6_REST,
        'connectors': list(el.CONNECTORS),
        'pockets': {k: [v[0], v[1], list(v[2]) if v[2] else None] for k, v in el.POCKETS.items()},
        'pocket_tiles': {k: {room: list(ts) for room, ts in v.items()} for k, v in el.POCKET_TILES.items()},
        'region_patches': {k: [list(p) for p in v] for k, v in el.REGION_PATCHES.items()},
        'hookshot_routes': hookshot_logic.ROUTES,
        'shop_inside': sanity_inside(shopsanity),
        'trendy_inside': sanity_inside(trendsanity),
        'bush_type': bushes.BUSH_TYPE,
        'rock_type': rocks.ROCK_TYPE,
        'apple_stand': apple_trees.STAND,
    }


def c_literal(s):
    out = []
    for ch in s:
        out.append('\\\\' if ch == '\\' else '\\"' if ch == '"' else ch)
    return '"' + ''.join(out) + '"'


def render():
    text = json.dumps(data(), ensure_ascii=True, separators=(',', ':'))
    parts = [text[i:i + 2000] for i in range(0, len(text), 2000)]  # (MSVC: a string literal stays under 16 KB)
    lines = ['// Generated by tools/rando/export_entrance_data.py from tools/rando/entrance_data.yml and the tables of',
             '// entrance_logic.py, hookshot_logic.py, shopsanity.py, trendsanity.py, bushes.py, rocks.py and',
             "// apple_trees.py. Don't edit: rerun the script.",
             '#include "entrances.h"', '', 'namespace rando {', 'namespace solve {', '',
             'static const char *const kParts[] = {']
    lines += ['    ' + c_literal(p) + ',' for p in parts]
    lines += ['};', '',
              'std::string entrance_tables_json() {',
              '    std::string s;',
              '    for (const char *p : kParts) s += p;',
              '    return s;',
              '}', '', '}  // namespace solve', '}  // namespace rando', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print(f'{os.path.relpath(OUT, ROOT)} is out of date: run tools/rando/export_entrance_data.py')
            return 1
        print(f'{os.path.relpath(OUT, ROOT)}: up to date')
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
